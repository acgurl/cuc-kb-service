def norm(text):
    return re.sub(r"\s+", "", text or "")


def main():
    chunks_path = ROOT / "data" / "chunks.jsonl"
    chunks = [json.loads(line) for line in chunks_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    active = [c for c in chunks if c.get("status") == "active"]
    by_doc = {}
    for chunk in active:
        by_doc.setdefault(chunk["doc_id"], []).append(chunk)

    problems = 0
    curated = []
    for case_id, query, expected, keywords in CASES:
        docs = [d for d, cs in by_doc.items() if any(e in cs[0]["doc_title"] for e in expected)]
        if not docs:
            print("DOC MISSING", case_id, expected)
            problems += 1
            continue
        hay = norm("\n".join(c["text"] for d in docs for c in by_doc[d]))
        if not any(norm(k) in hay for k in keywords):
            print("KEYWORD MISSING", case_id, query, keywords)
            problems += 1
            continue
        hit_docs = [d for d in docs if any(norm(k) in norm(c["text"]) for c in by_doc[d] for k in keywords)]
        others = sorted(
            {cs[0]["doc_title"][:40] for d, cs in by_doc.items() if d not in docs
             and any(norm(k) in norm(c["text"]) for c in cs for k in keywords)}
        )
        if others:
            print("KEYWORD ALSO IN", case_id, keywords, "->", others[:4])
        assistants = [a for a in by_doc[hit_docs[0]][0].get("assistants", []) if a != "shared"]
        specific = [a for a in assistants if a != "问道中传"]
        curated.append({
            "id": case_id,
            "query": query,
            "expected_docs": expected,
            "keywords": keywords,
            "intended_assistant": (specific or assistants or ["问道中传"])[0],
        })

    no_answer = []
    for case_id, query, probes in NO_ANSWER:
        hits = [p for p in probes if any(p in c["text"] for c in active)]
        if hits:
            print("NO-ANSWER PROBE FOUND", case_id, query, hits)
            problems += 1
            continue
        no_answer.append({"id": case_id, "query": query})

    dataset = {
        "meta": {
            "name": "CUC KB held-out v1",
            "created": "2026-11-01",
            "chunks_md5_source": "data/chunks.jsonl (production 2026-11-01)",
            "note": "仅使用 v1-v5 未引用过的文档出题；口语化改写，答案关键词逐条在原文核验；未参与任何调参",
        },
        "curated": curated,
        "no_answer": no_answer,
    }
    out = Path(__file__).with_name("dataset_heldout_v1.json")
    out.write_text(json.dumps(dataset, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"curated={len(curated)} no_answer={len(no_answer)} problems={problems} -> {out}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
