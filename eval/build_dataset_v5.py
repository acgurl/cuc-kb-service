titles = {r["doc_title"] for r in rows}


def norm(x):
    return re.sub(r"\s+", "", x or "")


problems = []
for case in cur + short + cit:
    matched = {t for t in titles if any(e in t for e in case["expected_docs"])}
    if not matched:
        problems.append(("NO_DOC", case["id"], case["expected_docs"]))
    for kw in case.get("keywords", []):
        ok = any(norm(kw) in norm(r["text"]) for r in rows if r["doc_title"] in matched)
        if not ok:
            problems.append(("NO_KW", case["id"], kw))
    if "expected_page" in case:
        ok = any(
            r["doc_title"] in matched
            and int(r["page_start"]) <= case["expected_page"] <= int(r["page_end"])
            and norm(case["page_phrase"]) in norm(r["text"])
            for r in rows
        )
        if not ok:
            problems.append(("NO_PAGE", case["id"], case["expected_page"], case["page_phrase"]))
print("problems", len(problems))
